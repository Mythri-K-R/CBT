/**
 * ExamSphere Service Worker — Offline Answer Recovery (Feature 3)
 *
 * RESPONSIBILITIES
 *   1. Intercept POST /exam/save-response calls
 *   2. On network failure: store answer in IndexedDB, return synthetic success
 *   3. On reconnect: Background Sync API drains the queue via POST sync-queue
 *   4. Handle explicit SYNC_NOW messages from the page (sleep/wake, reconnect event)
 *
 * RECOVERY SCENARIOS
 *   Browser refresh       — IndexedDB survives; Background Sync re-registers on next SW activation
 *   Network reconnect     — Background Sync fires automatically
 *   Laptop sleep/wake     — Background Sync fires when browser regains connectivity
 *   Browser restart       — IndexedDB survives; sync fires on next page load if online
 *   Redis restart         — No SW impact; backend DB fallback handles timer sync
 *
 * INDEXEDDB SCHEMA
 *   Database : ExamSphere  (version 1)
 *   Store    : offline_answers
 *     keyPath : offline_id  (UUID v4 generated by this SW)
 *     Indexes : by_attempt  → attempt_uuid  (non-unique, for grouping)
 *               by_synced   → synced         (non-unique, for filtering)
 *
 *   Record shape:
 *     offline_id         string   UUID v4
 *     attempt_uuid       string   exam attempt UUID
 *     test_question_id   int
 *     selected_answer    string|null
 *     status             string   answered|not_answered|marked_review|answered_marked_review
 *     time_spent_seconds int
 *     client_timestamp   string   ISO-8601 — when the student made this choice
 *     synced             boolean  false = pending
 *     retry_count        int      incremented on 5xx; entry deleted after MAX_RETRIES
 *
 * CONFLICT RESOLUTION (server-side)
 *   The server compares client_timestamp against last_modified_at in DB.
 *   Stale / expired rejections are treated as success by the SW (server is authoritative).
 *   5xx responses trigger a retry via Background Sync.
 */

'use strict';

const SW_VERSION  = '1.0.0';
const IDB_NAME    = 'ExamSphere';
const IDB_VERSION = 1;
const STORE_NAME  = 'offline_answers';
const SYNC_TAG    = 'exam-answer-sync';
const MAX_RETRIES = 5;
const MAX_BATCH   = 50;   // answers per sync-queue POST

// ── IndexedDB ──────────────────────────────────────────────────────────────────

function openDB() {
  return new Promise((resolve, reject) => {
    const req = indexedDB.open(IDB_NAME, IDB_VERSION);

    req.onupgradeneeded = (e) => {
      const db = e.target.result;
      if (!db.objectStoreNames.contains(STORE_NAME)) {
        const store = db.createObjectStore(STORE_NAME, { keyPath: 'offline_id' });
        store.createIndex('by_attempt', 'attempt_uuid', { unique: false });
        store.createIndex('by_synced',  'synced',       { unique: false });
      }
    };

    req.onsuccess = (e) => resolve(e.target.result);
    req.onerror   = (e) => reject(e.target.error);
  });
}

async function upsertAnswer(record) {
  const db    = await openDB();
  const tx    = db.transaction(STORE_NAME, 'readwrite');
  const store = tx.objectStore(STORE_NAME);

  // Replace any earlier pending entry for the same (attempt, question) pair.
  // Keeps the queue lean and ensures we only ever sync the latest choice.
  const all = await idbGetAll(store.index('by_attempt'), record.attempt_uuid);
  for (const old of all) {
    if (old.test_question_id === record.test_question_id && !old.synced) {
      store.delete(old.offline_id);
    }
  }

  store.put(record);
  return txDone(tx);
}

async function getPendingForAttempt(attemptUuid) {
  const db  = await openDB();
  const tx  = db.transaction(STORE_NAME, 'readonly');
  const all = await idbGetAll(tx.objectStore(STORE_NAME).index('by_attempt'), attemptUuid);
  return all.filter(r => !r.synced);
}

async function getAllPendingAttemptUuids() {
  const db    = await openDB();
  const tx    = db.transaction(STORE_NAME, 'readonly');
  const all   = await idbGetAll(tx.objectStore(STORE_NAME));
  const uuids = [...new Set(all.filter(r => !r.synced).map(r => r.attempt_uuid))];
  return uuids;
}

async function removeSynced(offlineIds) {
  if (!offlineIds.length) return;
  const db    = await openDB();
  const tx    = db.transaction(STORE_NAME, 'readwrite');
  const store = tx.objectStore(STORE_NAME);
  for (const id of offlineIds) { store.delete(id); }
  return txDone(tx);
}

async function bumpRetries(offlineIds) {
  if (!offlineIds.length) return;
  const db    = await openDB();
  const tx    = db.transaction(STORE_NAME, 'readwrite');
  const store = tx.objectStore(STORE_NAME);
  for (const id of offlineIds) {
    const get = store.get(id);
    get.onsuccess = (e) => {
      const r = e.target.result;
      if (!r) return;
      r.retry_count = (r.retry_count || 0) + 1;
      if (r.retry_count >= MAX_RETRIES) {
        store.delete(id);   // Permanent failure — discard after MAX_RETRIES
      } else {
        store.put(r);
      }
    };
  }
  return txDone(tx);
}

// Utility: IDBIndex/IDBObjectStore.getAll() wrapped as Promise
function idbGetAll(source, query) {
  return new Promise((resolve, reject) => {
    const req = query !== undefined ? source.getAll(query) : source.getAll();
    req.onsuccess = (e) => resolve(e.target.result || []);
    req.onerror   = (e) => reject(e.target.error);
  });
}

function txDone(tx) {
  return new Promise((resolve, reject) => {
    tx.oncomplete = resolve;
    tx.onerror    = (e) => reject(e.target.error);
  });
}

// ── UUID helper ────────────────────────────────────────────────────────────────

function generateUuid() {
  // RFC 4122 v4, using crypto.getRandomValues where available
  if (typeof crypto !== 'undefined' && crypto.getRandomValues) {
    return ([1e7] + -1e3 + -4e3 + -8e3 + -1e11).replace(/[018]/g, (c) => {
      return (c ^ (crypto.getRandomValues(new Uint8Array(1))[0] & (15 >> (c / 4)))).toString(16);
    });
  }
  // Fallback (should never be needed in modern browsers)
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    return (c === 'x' ? r : (r & 0x3) | 0x8).toString(16);
  });
}

// ── Request parsing ────────────────────────────────────────────────────────────

async function parseAnswerFromRequest(request) {
  try {
    const body = await request.clone().json();
    if (!body || !body.attempt_uuid || !body.test_question_id) return null;
    return {
      offline_id:         generateUuid(),
      attempt_uuid:       String(body.attempt_uuid),
      test_question_id:   Number(body.test_question_id),
      selected_answer:    body.selected_answer ?? null,
      status:             String(body.status || 'not_answered'),
      time_spent_seconds: Number(body.time_spent_seconds || 0),
      client_timestamp:   new Date().toISOString(),
      synced:             false,
      retry_count:        0,
    };
  } catch {
    return null;
  }
}

// ── Sync ───────────────────────────────────────────────────────────────────────

async function syncAttempt(attemptUuid) {
  const pending = await getPendingForAttempt(attemptUuid);
  if (!pending.length) return;

  // Process in batches of MAX_BATCH (prevents oversized payloads)
  for (let offset = 0; offset < pending.length; offset += MAX_BATCH) {
    const batch      = pending.slice(offset, offset + MAX_BATCH);
    const batchIds   = batch.map(r => r.offline_id);
    let   response;

    try {
      response = await fetch(`/api/test/exam/${encodeURIComponent(attemptUuid)}/sync-queue`, {
        method:  'POST',
        headers: {
          'Content-Type': 'application/json',
          'Accept':       'application/json',
          'X-Requested-With': 'XMLHttpRequest',
        },
        body: JSON.stringify({ answers: batch }),
      });
    } catch {
      // Still offline
      await bumpRetries(batchIds);
      throw new Error('Network unavailable during sync');
    }

    if (response.status >= 500) {
      await bumpRetries(batchIds);
      throw new Error(`Server error ${response.status} — will retry via BackgroundSync`);
    }

    if (response.status === 404 || response.status === 422) {
      // Exam not found or validation failure — discard unrecoverable answers
      await removeSynced(batchIds);
      return;
    }

    if (response.status === 429) {
      // Rate limited — back off, let Background Sync retry
      await bumpRetries(batchIds);
      throw new Error('Rate limited during sync');
    }

    // 2xx: remove all in batch from IDB regardless of per-answer rejection reason.
    // 'stale' and 'expired' rejections are authoritative server decisions — no retry.
    await removeSynced(batchIds);

    if (typeof response.json === 'function') {
      const data = await response.json().catch(() => ({}));
      if (data.synced !== undefined) {
        console.debug(`[ExamSW] Synced ${data.synced}/${batch.length} for ${attemptUuid.slice(0, 8)}…`);
      }
    }
  }
}

async function syncAllAttempts() {
  const uuids = await getAllPendingAttemptUuids();
  let lastError;

  for (const uuid of uuids) {
    try {
      await syncAttempt(uuid);
    } catch (e) {
      // Continue trying other attempts; re-throw at the end so Background Sync
      // knows to schedule a retry.
      lastError = e;
      console.warn(`[ExamSW] Sync failed for attempt ${uuid.slice(0, 8)}…:`, e.message);
    }
  }

  if (lastError) throw lastError;
}

// ── Fetch intercept ────────────────────────────────────────────────────────────

self.addEventListener('fetch', (event) => {
  const { request } = event;

  // Only intercept exam save-response POST calls
  if (request.method !== 'POST') return;
  const url = new URL(request.url);
  if (!url.pathname.endsWith('/exam/save-response')) return;

  event.respondWith(handleSaveResponse(request));
});

async function handleSaveResponse(request) {
  // Parse the body BEFORE the network attempt (body stream can only be consumed once)
  const record = await parseAnswerFromRequest(request);

  let networkResponse;
  try {
    networkResponse = await fetch(request);
  } catch {
    // ── Offline / connection lost ─────────────────────────────────────────────
    if (record) {
      try {
        // Wrap IDB operations: if IndexedDB is unavailable (private/incognito mode,
        // storage quota exceeded, iOS WebKit quirks) this must NOT propagate —
        // an uncaught exception here rejects event.respondWith() and causes a
        // hard NetworkError on the exam page instead of a clean synthetic response.
        await upsertAnswer(record);
        await tryRegisterSync();
      } catch {
        // IDB unavailable — answer cannot be queued for later sync.
        // Still return synthetic success so the exam UI stays functional.
      }
    }
    // Return synthetic success — exam UI must not show an error for normal auto-saves
    return syntheticSaveResponse();
  }

  // ── Online: decide whether to also queue ─────────────────────────────────────

  if (networkResponse.ok) {
    // Clean online path — no queuing needed
    return networkResponse;
  }

  if (networkResponse.status === 422) {
    // Exam expired on server — return as-is, do not queue (exam has ended)
    return networkResponse;
  }

  if (networkResponse.status >= 400 && networkResponse.status < 500) {
    // Client error (auth, validation) — do not queue
    return networkResponse;
  }

  // 5xx or unexpected: queue the answer and return the original response
  // so the page knows the online save failed (but UI handles this gracefully)
  if (record) {
    try {
      await upsertAnswer(record);
      await tryRegisterSync();
    } catch {
      // IDB unavailable — cannot queue; fall through and return the 5xx response
    }
  }
  return networkResponse;
}

function syntheticSaveResponse() {
  return new Response(
    JSON.stringify({ saved: true, offline: true, server_time: new Date().toISOString() }),
    { status: 200, headers: { 'Content-Type': 'application/json' } }
  );
}

async function tryRegisterSync() {
  try {
    await self.registration.sync.register(SYNC_TAG);
  } catch {
    // Background Sync API not available (Firefox, some mobile browsers).
    // The SW will still sync on the next SYNC_NOW message from the page.
  }
}

// ── Background Sync ────────────────────────────────────────────────────────────

self.addEventListener('sync', (event) => {
  if (event.tag === SYNC_TAG) {
    // waitUntil: if syncAllAttempts() throws, the browser will retry the sync tag
    event.waitUntil(syncAllAttempts());
  }
});

// ── Message API ────────────────────────────────────────────────────────────────
//
// The page sends: navigator.serviceWorker.controller.postMessage({ type: 'SYNC_NOW' })
// Triggered on: window online event, visibilitychange, page load (as fallback for
// browsers without Background Sync API support).

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SYNC_NOW') {
    // Respond to let the page know sync was triggered
    event.waitUntil(
      syncAllAttempts()
        .then(() => event.source?.postMessage({ type: 'SYNC_DONE', success: true }))
        .catch(() => event.source?.postMessage({ type: 'SYNC_DONE', success: false }))
    );
  }

  // Page sends PENDING_COUNT to get how many answers are queued (for UI badge)
  if (event.data && event.data.type === 'PENDING_COUNT') {
    getAllPendingAttemptUuids().then(async (uuids) => {
      let total = 0;
      for (const uuid of uuids) {
        const p = await getPendingForAttempt(uuid);
        total += p.length;
      }
      event.source?.postMessage({ type: 'PENDING_COUNT', count: total });
    }).catch(() => {
      event.source?.postMessage({ type: 'PENDING_COUNT', count: 0 });
    });
  }
});

// ── Lifecycle ──────────────────────────────────────────────────────────────────

self.addEventListener('install', () => {
  // Take over immediately — don't wait for old SW to unload
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  // Claim all existing clients immediately so fetch intercept applies to open tabs
  event.waitUntil(clients.claim());
});
